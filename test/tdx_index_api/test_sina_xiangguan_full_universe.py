def normalize_code(value: str) -> str:
    s = str(value).strip()
    s = re.sub(r"^(sh|sz|bj)\.?", "", s, flags=re.I)
    return s.zfill(6)


def load_tdx_current() -> pd.DataFrame:
    path = ROOT / "stock_list_master.json"
    if not path.exists():
        raise FileNotFoundError(
            f"Missing {path}; run go run . -mode list first"
        )
    data = json.loads(path.read_text(encoding="utf-8"))
    rows = []
    for item in data:
        code = normalize_code(item.get("code", ""))
        if len(code) == 6:
            rows.append({
                "code": code,
                "name": str(item.get("code_name", "")),
                "source": "tdx_current",
            })
    return pd.DataFrame(rows).drop_duplicates("code")


def load_delisted() -> pd.DataFrame:
    """Load the user-supplied historical delisted stock universe.

    This test deliberately does not call AKShare. The delisted-code file is
    checked into the test directory and is therefore deterministic/offline.
    """
    path = ROOT / "delisted_stock_codes.txt"
    if not path.exists():
        raise FileNotFoundError(f"Missing supplied delisted list: {path}")

    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        code = line.strip()
        if not code or code.startswith("#"):
            continue
        code = normalize_code(code)
        if len(code) != 6 or not code.isdigit():
            raise ValueError(f"Invalid delisted stock code: {code!r}")
        rows.append({
            "code": code,
            "name": "",
            "source": "delisted",
            "list_date": "",
            "delist_date": "",
        })

    return (
        pd.DataFrame(rows)
        .drop_duplicates(subset=["code"])
        .reset_index(drop=True)
    )

def build_universe() -> pd.DataFrame:
    current = load_tdx_current()
    current["list_date"] = ""
    current["delist_date"] = ""

    delisted = load_delisted()

    universe = pd.concat([
        current[["code", "name", "source", "list_date", "delist_date"]],
        delisted[["code", "name", "source", "list_date", "delist_date"]],
    ], ignore_index=True)

    universe["priority"] = universe["source"].map(
        {"tdx_current": 0, "delisted": 1}
    )
    universe = (
        universe.sort_values(["code", "priority"])
        .drop_duplicates("code", keep="first")
        .drop(columns=["priority"])
        .sort_values("code")
        .reset_index(drop=True)
    )
    return universe


def cache_path(code: str) -> Path:
    return CACHE / f"{code}.html"


def fetch_html(session: requests.Session, code: str) -> tuple[str, str]:
    path = cache_path(code)
    if path.exists() and path.stat().st_size > 1000:
        return path.read_text(encoding="gb2312", errors="ignore"), "cache"

    url = f"{BASE}/corp/go.php/vCI_CorpXiangGuan/stockid/{code}.phtml"
    last_error = ""
    for attempt in range(RETRIES):
        try:
            if attempt:
                time.sleep(min(8.0, 0.8 * (2 ** (attempt - 1))))
            r = session.get(url, timeout=TIMEOUT)
            if r.status_code in (403, 429):
                last_error = f"HTTP {r.status_code}"
                continue
            r.raise_for_status()
            r.encoding = "gb2312"
            text = r.text
            if len(text) < 1000:
                last_error = f"short response {len(text)}"
                continue
            path.write_text(text, encoding="gb2312", errors="ignore")
            if DELAY:
                time.sleep(DELAY)
            return text, "network"
        except Exception as exc:
            last_error = repr(exc)
    raise RuntimeError(last_error or "unknown error")


def find_xiangguan_table(soup: BeautifulSoup):
    required = {"指数名称", "指数代码", "进入日期", "退出日期"}
    for table in soup.find_all("table"):
        rows = table.find_all("tr")
        for row in rows[:4]:
            headers = {
                x.get_text(" ", strip=True)
                for x in row.find_all(["th", "td"])
            }
            if required.issubset(headers):
                return table
    return None


def parse_xiangguan(html: str, stock_code: str):
    soup = BeautifulSoup(html, "html.parser")
    table = find_xiangguan_table(soup)
    if table is None:
        return [], "parse_error"

    rows = table.find_all("tr")
    header_idx = None
    headers = []
    for i, row in enumerate(rows[:6]):
        vals = [x.get_text(" ", strip=True) for x in row.find_all(["th", "td"])]
        if {"指数名称", "指数代码", "进入日期", "退出日期"}.issubset(set(vals)):
            header_idx = i
            headers = vals
            break

    if header_idx is None:
        return [], "parse_error"

    pos = {h: i for i, h in enumerate(headers)}
    result = []

    for row in rows[header_idx + 1:]:
        vals = [x.get_text(" ", strip=True) for x in row.find_all(["th", "td"])]
        if len(vals) < len(headers):
            continue

        index_name = vals[pos["指数名称"]].strip()
        index_code = vals[pos["指数代码"]].strip()
        start = vals[pos["进入日期"]].strip()
        end = vals[pos["退出日期"]].strip()

        if not index_code:
            continue

        canonical = INDEX_ALIASES.get(index_code, index_code)
        if canonical not in TARGET_INDEXES:
            continue

        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", start):
            continue
        if end and not re.fullmatch(r"\d{4}-\d{2}-\d{2}", end):
            continue

        result.append({
            "index_id": canonical,
            "index_name": TARGET_INDEXES[canonical],
            "stock_id": stock_code,
            "start_date": start,
            "end_date": end or "",
            "raw_index_code": index_code,
            "raw_index_name": index_name,
        })

    return result, "ok"



def fetch_component_page(
    session: requests.Session,
    index_id: str,
    kind: str,
    page: int,
) -> str:
    path = (
        "vII_HistoryComponent.php"
        if kind == "history"
        else "vII_NewestComponent.php"
    )
    url = f"{BASE}/corp/view/{path}?page={page}&indexid={index_id}"
    r = session.get(url, timeout=TIMEOUT)
    r.raise_for_status()
    r.encoding = "gb2312"
    return r.text


def component_page_count(html: str) -> int:
    pages = [int(x) for x in re.findall(r"[?&]page=(\d+)", html)]
    return max(pages, default=1)


def parse_component_codes(html: str) -> set[str]:
    soup = BeautifulSoup(html, "html.parser")
    for table in soup.find_all("table"):
        rows = table.find_all("tr")
        for row in rows[:6]:
            headers = [
                x.get_text(" ", strip=True)
                for x in row.find_all(["th", "td"])
            ]
            if "品种代码" not in headers:
                continue

            code_pos = headers.index("品种代码")
            codes = set()
            for data_row in rows[rows.index(row) + 1:]:
                vals = [
                    x.get_text(" ", strip=True)
                    for x in data_row.find_all(["th", "td"])
                ]
                if len(vals) <= code_pos:
                    continue
                code = normalize_code(vals[code_pos])
                if re.fullmatch(r"\d{6}", code):
                    codes.add(code)
            if codes:
                return codes
    return set()


def collect_a_candidates() -> tuple[dict[str, set[str]], list[dict]]:
    """
    Build A = HistoryComponent ∪ NewestComponent candidate stocks.

    This only discovers candidate stock codes. The actual historical
    intervals are still parsed from the same XiangGuan pages used by B,
    so the A/B comparison has identical normalization semantics.
    """
    session = requests.Session()
    session.headers.update({
        "User-Agent": UA,
        "Accept-Language": "zh-CN,zh;q=0.9,en;q=0.8",
    })

    candidates = {}
    errors = []

    for index_id in TARGET_INDEXES:
        codes = set()
        for kind in ("history", "newest"):
            try:
                first = fetch_component_page(session, index_id, kind, 1)
                pages = component_page_count(first)
                for page in range(1, pages + 1):
                    html = (
                        first
                        if page == 1
                        else fetch_component_page(
                            session, index_id, kind, page
                        )
                    )
                    codes.update(parse_component_codes(html))
                print(
                    f"A candidates {index_id} {kind}: "
                    f"pages={pages} stocks={len(codes)}",
                    flush=True,
                )
            except Exception as exc:
                errors.append({
                    "index_id": index_id,
                    "kind": kind,
                    "error": repr(exc),
                })

        candidates[index_id] = codes
        print(
            f"A candidates {index_id}: union={len(codes)}",
            flush=True,
        )

    return candidates, errors


def build_a_from_xiangguan(
    candidates: dict[str, set[str]],
) -> tuple[pd.DataFrame, list[dict]]:
    """
    Convert A candidate stocks into normalized intervals.

    Reuse the B XiangGuan cache whenever possible. If A discovers a stock
    that was not present in the B universe, fetch that stock page here.
    """
    rows = []
    errors = []
    session = requests.Session()
    session.headers.update({
        "User-Agent": UA,
        "Accept-Language": "zh-CN,zh;q=0.9,en;q=0.8",
    })

    all_codes = sorted(set().union(*candidates.values()))
    for n, code in enumerate(all_codes, 1):
        try:
            html, _ = fetch_html(session, code)
            parsed, status = parse_xiangguan(html, code)
            if status != "ok":
                errors.append({
                    "code": code,
                    "status": status,
                    "error": "XiangGuan parse failed for A candidate",
                })
                continue

            wanted = set()
            for index_id, codes in candidates.items():
                if code in codes:
                    wanted.add(index_id)

            rows.extend(
                row for row in parsed
                if row["index_id"] in wanted
            )
        except Exception as exc:
            errors.append({
                "code": code,
                "status": "http_error",
                "error": repr(exc),
            })

        if n % 100 == 0 or n == len(all_codes):
            print(
                f"A XiangGuan [{n}/{len(all_codes)}] "
                f"intervals={len(rows)} errors={len(errors)}",
                flush=True,
            )

    columns = ["index_id", "stock_id", "start_date", "end_date"]
    df = pd.DataFrame(rows)
    if df.empty:
        df = pd.DataFrame(columns=columns)
    else:
        df = (
            df[columns]
            .drop_duplicates()
            .sort_values(columns)
            .reset_index(drop=True)
        )
    return df, errors


def run_ab_diff(
    a_df: pd.DataFrame,
    b_df: pd.DataFrame,
) -> dict:
    diff_dir = OUT / "ab_diff"
    diff_dir.mkdir(parents=True, exist_ok=True)
    key = ["index_id", "stock_id", "start_date", "end_date"]

    summary_rows = []
    all_a_only = []
    all_b_only = []

    for index_id in TARGET_INDEXES:
        a = a_df[a_df.index_id == index_id][key].drop_duplicates()
        b = b_df[b_df.index_id == index_id][key].drop_duplicates()

        merged = a.merge(
            b,
            on=key,
            how="outer",
            indicator=True,
        )
        a_only = (
            merged[merged["_merge"] == "left_only"]
            .drop(columns="_merge")
            .sort_values(key)
        )
        b_only = (
            merged[merged["_merge"] == "right_only"]
            .drop(columns="_merge")
            .sort_values(key)
        )

        a_only.to_csv(
            diff_dir / f"{index_id}_a_minus_b.csv",
            index=False,
            encoding="utf-8-sig",
        )
        b_only.to_csv(
            diff_dir / f"{index_id}_b_minus_a.csv",
            index=False,
            encoding="utf-8-sig",
        )

        for frame, side in ((a_only, "A-B"), (b_only, "B-A")):
            if not frame.empty:
                temp = frame.copy()
                temp["diff"] = side
                if side == "A-B":
                    all_a_only.append(temp)
                else:
                    all_b_only.append(temp)

        a_stocks = set(a.stock_id)
        b_stocks = set(b.stock_id)
        summary_rows.append({
            "index_id": index_id,
            "a_intervals": len(a),
            "b_intervals": len(b),
            "a_only_intervals": len(a_only),
            "b_only_intervals": len(b_only),
            "a_stocks": len(a_stocks),
            "b_stocks": len(b_stocks),
            "a_only_stocks": len(a_stocks - b_stocks),
            "b_only_stocks": len(b_stocks - a_stocks),
        })

    summary_df = pd.DataFrame(summary_rows)
    summary_df.to_csv(
        diff_dir / "all_indices_diff_summary.csv",
        index=False,
        encoding="utf-8-sig",
    )

    a_all = (
        pd.concat(all_a_only, ignore_index=True)
        if all_a_only
        else pd.DataFrame(columns=key + ["diff"])
    )
    b_all = (
        pd.concat(all_b_only, ignore_index=True)
        if all_b_only
        else pd.DataFrame(columns=key + ["diff"])
    )
    a_all.to_csv(
        diff_dir / "all_a_minus_b.csv",
        index=False,
        encoding="utf-8-sig",
    )
    b_all.to_csv(
        diff_dir / "all_b_minus_a.csv",
        index=False,
        encoding="utf-8-sig",
    )

    return {
        "summary": summary_rows,
        "a_minus_b_intervals": len(a_all),
        "b_minus_a_intervals": len(b_all),
        "diff_dir": str(diff_dir),
    }



def audit_b_only(
    a_df: pd.DataFrame,
    b_df: pd.DataFrame,
    universe: pd.DataFrame,
) -> dict:
    """Audit intervals found by B but missed by A candidate discovery."""
    audit_dir = OUT / "ab_diff"
    audit_dir.mkdir(parents=True, exist_ok=True)
    key = ["index_id", "stock_id", "start_date", "end_date"]

    a_keys = set(map(tuple, a_df[key].itertuples(index=False, name=None)))
    b_tuples = b_df[key].apply(tuple, axis=1)
    b_only = b_df[~b_tuples.isin(a_keys)][key].copy()

    source_map = universe.set_index("code")["source"].to_dict()

    if b_only.empty:
        detail = pd.DataFrame(columns=[
            *key, "source", "interval_count_for_stock",
            "first_start_for_stock", "last_end_for_stock",
        ])
    else:
        counts = b_only.groupby(["index_id", "stock_id"]).size().rename(
            "interval_count_for_stock"
        )
        first_start = b_only.groupby(["index_id", "stock_id"])["start_date"].min().rename(
            "first_start_for_stock"
        )
        last_end = b_only.groupby(["index_id", "stock_id"])["end_date"].max().rename(
            "last_end_for_stock"
        )
        detail = b_only.merge(counts.reset_index(), on=["index_id", "stock_id"])
        detail = detail.merge(first_start.reset_index(), on=["index_id", "stock_id"])
        detail = detail.merge(last_end.reset_index(), on=["index_id", "stock_id"])
        detail["source"] = detail["stock_id"].map(source_map).fillna("unknown")
        detail = detail.sort_values(
            ["index_id", "first_start_for_stock", "stock_id", "start_date"]
        ).reset_index(drop=True)

    summary_rows = []
    for index_id in TARGET_INDEXES:
        g = detail[detail.index_id == index_id]
        stocks = set(g.stock_id)
        summary_rows.append({
            "index_id": index_id,
            "b_only_intervals": len(g),
            "b_only_stocks": len(stocks),
            "current_stocks": sum(source_map.get(x) == "tdx_current" for x in stocks),
            "delisted_only_stocks": sum(source_map.get(x) == "delisted" for x in stocks),
            "earliest_start": g.start_date.min() if not g.empty else "",
            "latest_start": g.start_date.max() if not g.empty else "",
            "open_ended_intervals": int((g.end_date == "").sum()) if not g.empty else 0,
        })
    summary = pd.DataFrame(summary_rows)

    detail.to_csv(audit_dir / "b_only_stock_audit.csv", index=False, encoding="utf-8-sig")
    summary.to_csv(audit_dir / "b_only_summary.csv", index=False, encoding="utf-8-sig")

    samples = []
    for index_id in TARGET_INDEXES:
        g = detail[detail.index_id == index_id]
        for label, sg in (
            ("earliest", g.sort_values(["start_date", "stock_id"]).head(10)),
            ("latest", g.sort_values(["start_date", "stock_id"], ascending=False).head(10)),
            ("open_ended", g[g.end_date == ""].sort_values(["start_date", "stock_id"]).head(10)),
        ):
            if not sg.empty:
                samples.append(sg.assign(sample=label))
    sample_df = (
        pd.concat(samples, ignore_index=True)
        if samples else detail.head(0).assign(sample=pd.Series(dtype=str))
    )
    sample_df.to_csv(
        audit_dir / "b_only_representative_samples.csv",
        index=False,
        encoding="utf-8-sig",
    )

    a_only = []
    for index_id in TARGET_INDEXES:
        a = a_df[a_df.index_id == index_id][key].drop_duplicates()
        b = b_df[b_df.index_id == index_id][key].drop_duplicates()
        merged = a.merge(b, on=key, how="outer", indicator=True)
        x = merged[merged["_merge"] == "left_only"].drop(columns="_merge")
        if not x.empty:
            a_only.append(x)
    a_only_df = pd.concat(a_only, ignore_index=True) if a_only else pd.DataFrame(columns=key)
    a_only_df.to_csv(
        audit_dir / "a_only_intervals_detail.csv",
        index=False,
        encoding="utf-8-sig",
    )

    print()
    print("=" * 72)
    print("B-ONLY AUDIT")
    print("=" * 72)
    print(summary.to_string(index=False))

    return {
        "b_only_intervals": len(detail),
        "b_only_stocks": int(detail.stock_id.nunique()) if not detail.empty else 0,
        "summary": summary.to_dict(orient="records"),
        "audit_files": [
            str(audit_dir / "b_only_stock_audit.csv"),
            str(audit_dir / "b_only_summary.csv"),
            str(audit_dir / "b_only_representative_samples.csv"),
            str(audit_dir / "a_only_intervals_detail.csv"),
        ],
    }



